import {test,expect,type Page} from '@playwright/test';
const saved=(page:Page)=>page.evaluate(()=>JSON.parse(localStorage.getItem('circuits-project')!));
test('resistor quick-unit selection changes real ohms and one undo leaves original wires',async({page})=>{
 await page.goto('/');
 const before=await saved(page);
 await page.locator('.item[data-part="r1"]').click();
 await expect(page.locator('.quick-properties [data-quick-field="value-unit"]')).toHaveValue('ohm');
 await page.locator('.quick-properties [data-quick-field="value-unit"]').selectOption('k');
 let p=await saved(page);
 expect(p.parts.find((x:{id:string})=>x.id==='r1').value).toBe(330000);
 expect(p.parts.find((x:{id:string})=>x.id==='r1').resistanceUnit).toBe('k');
 expect(p.wires).toEqual(before.wires);
 await expect(page.locator('#value')).toHaveValue('330');
 await expect(page.locator('#value-unit')).toHaveValue('k');
 await page.locator('[data-action="undo"]').click();
 p=await saved(page);
 expect(p.parts.find((x:{id:string})=>x.id==='r1').value).toBe(330);
 expect(p.parts.find((x:{id:string})=>x.id==='r1').resistanceUnit).toBeUndefined();
 await page.locator('[data-action="redo"]').click();
 await page.locator('.item[data-part="r1"]').click();
 await page.locator('.quick-properties [data-quick-field="value"]').fill('1.5');
 await page.locator('.quick-properties [data-quick-field="value"]').press('Tab');
 p=await saved(page);
 expect(p.parts.find((x:{id:string})=>x.id==='r1').value).toBe(1500);
 expect(p.wires).toEqual(before.wires);
 await expect(page.locator('#value')).toHaveValue('1.5');
});
test('resistor SI unit edit persists on reload and returns to bare ohms',async({page})=>{
 await page.goto('/');
 await page.locator('.item[data-part="r1"]').click();
 await page.locator('#value').fill('4.7');
 await page.locator('#value').press('Tab');
 await page.locator('#value-unit').selectOption('M');
 const baseline=await saved(page);
 expect(baseline.parts.find((p:{id:string})=>p.id==='r1').value).toBe(4700000);
 await page.reload();
 await page.locator('.item[data-part="r1"]').click();
 await expect(page.locator('#value-unit')).toHaveValue('M');
 await expect(page.locator('#value')).toHaveValue('4.7');
 await page.locator('#value-unit').selectOption('ohm');
 const next=await saved(page);
 expect(next.parts.find((p:{id:string})=>p.id==='r1').value).toBe(4.7);
 expect(next.parts.find((p:{id:string})=>p.id==='r1').resistanceUnit).toBeUndefined();
 expect(next.wires).toEqual(baseline.wires);
});
