import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
let source=readFileSync('src/main.ts','utf8');
const bytes=Buffer.from(source);
const sha=createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');
if(sha!=='7e0a2194c338b6bfdc423de14cae546223e85d63')throw Error(`Unexpected main.ts base: ${sha}`);
const old='if(!drag&&!bendDrag&&!segmentDrag&&!endpointDrag&&!marquee&&!panDrag&&!wiring&&!spaceHeld)return;';
if(source.split(old).length!==2)throw Error('Unexpected cancel guard');
writeFileSync('src/main.ts',source.replace(old,'if(!drag&&!bendDrag&&!segmentDrag&&!endpointDrag&&!marquee&&!panDrag&&!wireDrag&&!wiring&&!spaceHeld)return;'));
let doc=readFileSync('docs/ALPHA11.md','utf8');
doc=doc.replace('第二批增加 13 项纯状态机测试','第二批增加 14 项纯逻辑测试（含继承事件属性快照回归）');
doc=doc.replace('三引擎运行同一组确定性 PointerEvent 轨迹','另有 `e2e/pointer-recovery.spec.ts` 的 3 个场景检查尚未拖动就取消的引脚操作不会污染下一次元件拖动，第二批合计 29 个浏览器场景。\n\n三引擎运行同一组确定性 PointerEvent 轨迹');
writeFileSync('docs/ALPHA11.md',doc);
